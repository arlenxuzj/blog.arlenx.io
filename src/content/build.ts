import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { compile } from '@mdx-js/mdx';
import { slug } from 'github-slugger';
import matter from 'gray-matter';
import readingTime from 'reading-time';
import rehypeAutolinkHeadings from 'rehype-autolink-headings';
import rehypePrism from 'rehype-prism-plus';
import rehypeUnwrapImages from 'rehype-unwrap-images';
import remarkDirective from 'remark-directive';
import remarkGfm from 'remark-gfm';
import {
  rehypeCodeTitle,
  rehypeImage,
  rehypeSectionize,
  rehypeSlug
} from '../lib/rehype';
import { remarkCallout } from '../lib/remark';
import type { ContentDocument, Page, Post, Snippet } from './types';

export async function compileDocument(
  filePath: string,
  source: string
): Promise<ContentDocument> {
  const { data, content } = matter(source);
  const error = (field: string): never => {
    throw new Error(`${filePath}: invalid or missing ${field}`);
  };
  for (const field of ['title', 'description']) {
    if (typeof data[field] !== 'string' || !data[field].trim()) error(field);
  }
  const date = (field: string) => {
    if (!(typeof data[field] === 'string' || data[field] instanceof Date))
      return error(field);
    const result = new Date(data[field]);
    if (Number.isNaN(result.getTime())) return error(field);
    return result.toISOString();
  };
  const group = filePath.split('/')[0];
  if (!['posts', 'snippets', 'pages'].includes(group))
    error('document directory');
  if (
    group !== 'pages' &&
    (!Array.isArray(data.tags) ||
      data.tags.some((tag: unknown) => typeof tag !== 'string'))
  )
    error('tags');
  if (
    group === 'snippets' &&
    (typeof data.language !== 'string' || !data.language.trim())
  )
    error('language');
  for (const field of ['wip', 'ignore', 'updateDateAtBuildTime']) {
    if (data[field] !== undefined && typeof data[field] !== 'boolean')
      error(field);
  }
  if (
    data.backgroundType !== undefined &&
    typeof data.backgroundType !== 'string'
  )
    error('backgroundType');
  const flattenedPath = filePath.replace(/\.mdx$/, '');
  const raw = {
    sourceFilePath: filePath,
    sourceFileName: path.posix.basename(filePath),
    sourceFileDir: path.posix.dirname(filePath),
    flattenedPath,
    contentType: 'mdx' as const
  };
  const createdAt = date('createdAt');
  const updatedAt =
    data.updatedAt === undefined ? undefined : date('updatedAt');
  // Only repository-owned MDX is compiled; never evaluate visitor-supplied code.
  const compiled = await compile(
    {
      value: content,
      path: filePath,
      data: { rawDocumentData: raw, frontmatter: data }
    },
    {
      outputFormat: 'function-body',
      remarkPlugins: [remarkGfm, remarkDirective, remarkCallout],
      rehypePlugins: [
        rehypeUnwrapImages,
        rehypeSlug,
        [
          rehypeAutolinkHeadings,
          { properties: { className: ['heading-anchor'] } }
        ],
        rehypeSectionize,
        rehypeImage,
        rehypeCodeTitle,
        [rehypePrism, { ignoreMissing: true, showLineNumbers: true }]
      ]
    }
  );
  const common = {
    _id: filePath,
    _raw: raw,
    title: data.title,
    description: data.description,
    createdAt,
    ...(updatedAt === undefined ? {} : { updatedAt }),
    ...(data.wip === undefined ? {} : { wip: data.wip }),
    ...(data.ignore === undefined ? {} : { ignore: data.ignore }),
    slug: flattenedPath.slice(group.length + 1),
    body: { raw: content, code: String(compiled) }
  };
  if (group === 'pages')
    return {
      ...common,
      type: 'Page',
      ...(data.updateDateAtBuildTime === undefined
        ? {}
        : { updateDateAtBuildTime: data.updateDateAtBuildTime })
    } as Page;
  const article = {
    ...common,
    tags: data.tags,
    ...(data.backgroundType === undefined
      ? {}
      : { backgroundType: data.backgroundType }),
    readingTime: readingTime(content),
    titleSlug: slug(data.title),
    fileName: raw.sourceFileName
  };
  return group === 'posts'
    ? ({ ...article, type: 'Post' } as Post)
    : ({ ...article, type: 'Snippet', language: data.language } as Snippet);
}

export async function buildContent() {
  const files = (await readdir('contents', { recursive: true }))
    .filter(file => file.endsWith('.mdx'))
    .sort();
  const documents = await Promise.all(
    files.map(async file =>
      compileDocument(
        file.split(path.sep).join('/'),
        await readFile(path.join('contents', file), 'utf8')
      )
    )
  );
  const output =
    `// Generated by npm run content. Do not edit.\nimport type { Page, Post, Snippet } from '../../src/content/types';\nexport type { Page, Post, Snippet } from '../../src/content/types';\n` +
    (['Page', 'Post', 'Snippet'] as const)
      .map(
        type =>
          `export const all${type}s = ${JSON.stringify(documents.filter(doc => doc.type === type))} as ${type}[];\n`
      )
      .join('');
  const target = '.generated/content/index.ts';
  await mkdir(path.dirname(target), { recursive: true });
  const previous = await readFile(target, 'utf8').catch(() => '');
  if (previous !== output) await writeFile(target, output);
  console.log(`Generated ${documents.length} MDX documents`);
  return documents;
}
